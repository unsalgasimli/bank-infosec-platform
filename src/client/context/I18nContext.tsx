/**
 * Intelligent translate function supporting:
 * - Direct lookup in catalog
 * - Whitespace preservation for clean JSX interpolation
 * - Punctuation tolerance (preserving :, ..., ?, .)
 * - Dynamic pattern matching for common metrics (Showing X of Y, X selected, etc.)
 */
export const translate = (text: string, language: AppLanguage): string => {
  if (language === 'en' || !text) return text;

  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Direct dictionary match
  const direct = catalog[language][trimmed];
  if (direct) {
    const leading = text.match(/^\s*/)?.[0] ?? '';
    const trailing = text.match(/\s*$/)?.[0] ?? '';
    return `${leading}${direct}${trailing}`;
  }

  // 2. Trailing punctuation matching (e.g. "Status:" -> "Status" + ":", "Loading..." -> "Loading" + "...")
  const punctMatch = trimmed.match(/^(.+?)([:.?!]+|\.{3})$/);
  if (punctMatch) {
    const base = punctMatch[1].trim();
    const punct = punctMatch[2];
    const baseTranslated = catalog[language][base];
    if (baseTranslated) {
      const leading = text.match(/^\s*/)?.[0] ?? '';
      const trailing = text.match(/\s*$/)?.[0] ?? '';
      return `${leading}${baseTranslated}${punct}${trailing}`;
    }
  }

  // 3. Dynamic patterns for metrics and status counts
  // "Showing X of Y items" / "Showing X of Y"
  const showingOfMatch = trimmed.match(/^Showing\s+(\d+)\s+of\s+(\d+)(?:\s+items)?$/i);
  if (showingOfMatch) {
    return text.replace(trimmed, `${showingOfMatch[2]} elementdən ${showingOfMatch[1]}-i göstərilir`);
  }

  // "Showing X items" / "Showing X tasks"
  const showingMatch = trimmed.match(/^Showing\s+(\d+)\s+(items|tasks|tickets|results)$/i);
  if (showingMatch) {
    const noun = showingMatch[2].toLowerCase() === 'tickets' ? 'tapşırıq' : 'element';
    return text.replace(trimmed, `${showingMatch[1]} ${noun} göstərilir`);
  }

  // "X items selected" / "X selected"
  const selectedMatch = trimmed.match(/^(\d+)\s+(?:items\s+)?selected$/i);
  if (selectedMatch) {
    return text.replace(trimmed, `${selectedMatch[1]} seçilib`);
  }

  // "Page X of Y"
  const pageMatch = trimmed.match(/^Page\s+(\d+)\s+of\s+(\d+)$/i);
  if (pageMatch) {
    return text.replace(trimmed, `Səhifə ${pageMatch[1]} / ${pageMatch[2]}`);
  }

  // "X% completed" / "X% done"
  const pctMatch = trimmed.match(/^(\d+)%\s+(?:completed|done)$/i);
  if (pctMatch) {
    return text.replace(trimmed, `${pctMatch[1]}% tamamlandı`);
  }

  // "Target: X"
  const targetMatch = trimmed.match(/^Target:\s*(.+)$/i);
  if (targetMatch) {
    return text.replace(trimmed, `Hədəf: ${targetMatch[1]}`);
  }

  // "Priority: X"
  const prioMatch = trimmed.match(/^Priority:\s*(.+)$/i);
  if (prioMatch) {
    const val = catalog[language][prioMatch[1].trim()] ?? prioMatch[1];
    return text.replace(trimmed, `Prioritet: ${val}`);
  }

  return text;
};

interface I18nContextValue {
  language: AppLanguage;
  locale: string;
  setLanguage: (language: AppLanguage) => void;
  t: (text: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const localizableAttributes = ['placeholder', 'title', 'aria-label', 'alt'] as const;

/** Applies the catalog to legacy JSX text, portal content, dropdowns, and newly rendered modals. */
const LocalizedDocument: React.FC<{ language: AppLanguage }> = ({ language }) => {
  const originalsRef = useRef(new WeakMap<Text, string>());

  useLayoutEffect(() => {
    const originals = originalsRef.current;
    let translating = false;

    const localizeElement = (element: Element) => {
      if (element.closest('[data-i18n-skip]') || ['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(element.tagName)) return;
      localizableAttributes.forEach((attribute) => {
        const originalAttribute = `data-i18n-${attribute}`;
        const original = element.getAttribute(originalAttribute) ?? element.getAttribute(attribute);
        if (!original) return;
        if (!element.hasAttribute(originalAttribute)) element.setAttribute(originalAttribute, original);
        const value = translate(original, language);
        if (element.getAttribute(attribute) !== value) element.setAttribute(attribute, value);
      });
    };

    const localizeText = (node: Text) => {
      const parent = node.parentElement;
      if (!parent || parent.closest('[data-i18n-skip]') || ['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(parent.tagName)) return;
      const original = originals.get(node) ?? node.data;
      if (!original.trim() || /[{}]/.test(original)) return;
      if (!originals.has(node)) originals.set(node, original);
      const value = translate(original, language);
      if (node.data !== value) node.data = value;
    };

    const localize = (root: Node) => {
      if (root.nodeType === Node.TEXT_NODE) localizeText(root as Text);
      if (root.nodeType === Node.ELEMENT_NODE) localizeElement(root as Element);
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
      for (let node = walker.nextNode(); node; node = walker.nextNode()) {
        if (node.nodeType === Node.TEXT_NODE) localizeText(node as Text);
        else localizeElement(node as Element);
      }
    };

    localize(document.body);

    const observer = new MutationObserver((mutations) => {
      if (translating) return;
      translating = true;
      mutations.forEach((mutation) => {
        if (mutation.type === 'childList') {
          mutation.addedNodes.forEach(localize);
        } else if (mutation.type === 'characterData' && mutation.target.nodeType === Node.TEXT_NODE) {
          localizeText(mutation.target as Text);
        } else if (mutation.type === 'attributes' && mutation.target.nodeType === Node.ELEMENT_NODE) {
          localizeElement(mutation.target as Element);
        }
      });
      translating = false;
    });

    observer.observe(document.body, {
      attributes: true,
      attributeFilter: [...localizableAttributes],
      characterData: true,
      childList: true,
      subtree: true,
    });

    return () => observer.disconnect();
  }, [language]);

  return null;
};

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === 'az' || stored === 'en' ? stored : 'az';
  });

  const setLanguage = useCallback((next: AppLanguage) => {
    setLanguageState(next);
    localStorage.setItem(STORAGE_KEY, next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = 'ltr';
    document.title = language === 'az'
      ? 'BankGRC | İnformasiya Təhlükəsizliyi və İdarəetmə Platforması'
      : 'BankGRC | Information Security & Governance Platform';
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: LOCALES[language],
    setLanguage,
    t: (text) => translate(text, language),
  }), [language, setLanguage]);

  return (
    <I18nContext.Provider value={value}>
      <LocalizedDocument language={language} />
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = (): I18nContextValue => {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used within an I18nProvider');
  return context;
};
